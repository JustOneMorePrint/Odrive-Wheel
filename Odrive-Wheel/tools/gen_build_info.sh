#!/bin/sh
# Writes the build id header used by sys.build?.
#
# Branch names may legally contain quotes, `$` and backticks, so the values never
# pass through make, a command line or C source text: they are read from git and
# the environment, and the header holds them as octal escapes only. The file is
# only rewritten when the id changes, so unchanged builds don't recompile its users.
#
# Usage: gen_build_info.sh <header>
# Environment, for CI where HEAD is a detached merge commit:
#   BUILD_GIT_BRANCH   branch to report instead of the checked-out one
#   BUILD_GIT_PR_HEAD  PR head commit, reported next to the built checkout
# An MSYS shell calling a native make must list BUILD_GIT_BRANCH in
# MSYS2_ENV_CONV_EXCL, or MSYS rewrites path-like values (x=/y becomes x=Y:/).
#
# Result: BUILD_ID = "<checkout>[-dirty] [head=<pr head>] branch=<branch>"

set -eu
export LC_ALL=C

header=$1
max_id_len=127  # the reply buffer in cmdparser.c holds 128 bytes

fail() {
    echo "gen_build_info.sh: $1" >&2
    exit 1
}

checkout=$(git describe --always --dirty --abbrev=12 --exclude='*' 2>/dev/null) || checkout=

branch=${BUILD_GIT_BRANCH:-}
if [ -z "$branch" ]; then
    if ref=$(git symbolic-ref -q HEAD 2>/dev/null); then
        branch=${ref#refs/heads/}
    elif [ -n "$checkout" ]; then
        branch=detached
    else
        branch=unknown
    fi
fi
case $branch in
    *[[:cntrl:]]*) fail "control character in branch name" ;;
    # git forbids ':' in branch names, but every MSYS rewrite produces one.
    *:*) fail "':' in branch name, probably rewritten by MSYS: add BUILD_GIT_BRANCH to MSYS2_ENV_CONV_EXCL" ;;
esac

id=${checkout:-unknown}

pr_head=${BUILD_GIT_PR_HEAD:-}
if [ -n "$pr_head" ]; then
    case $pr_head in
        *[!0-9a-fA-F]*) fail "BUILD_GIT_PR_HEAD is not a commit hash" ;;
    esac
    id="$id head=$(printf '%s' "$pr_head" | cut -c1-12)"
fi

id="$id branch=$branch"

if [ "$(printf '%s' "$id" | wc -c)" -gt "$max_id_len" ]; then
    id="$(printf '%s' "$id" | cut -b1-$((max_id_len - 3)))..."
fi

escaped=$(printf '%s' "$id" | od -An -v -to1 | tr -d ' \n' | sed 's/.../\\&/g')
content="// Generated by tools/gen_build_info.sh, do not edit.
#define BUILD_ID \"$escaped\""

existing=$(cat "$header" 2>/dev/null) || existing=
if [ "$content" != "$existing" ]; then
    printf '%s\n' "$content" > "$header.tmp"
    mv -f "$header.tmp" "$header"
    printf 'Build ID: %s\n' "$id"
fi
